/* Builds /work/<slug>/index.html — one real page per case study — and the
 * sitemap that lists them.
 *
 *   node scripts/build-work-pages.mjs         # write
 *   node scripts/build-work-pages.mjs --check # exit 1 if the output is stale
 *
 * WHY THIS EXISTS
 *
 * The case studies were dialogs inside "/". Everything that matters about a
 * case study — linking it in an application, posting it, having Google index
 * it, unfurling a preview that is about *that project* — needs a URL, and
 * they had none. Measured 2026-09-22: `site:bylx.dev` returned exactly one
 * result, the homepage, while five case studies sat in the markup.
 *
 * The copy is NOT duplicated by hand. index.html stays the single source:
 * each case-study modal carries data-work-slug / data-work-title /
 * data-work-description, and this script lifts the same body out and wraps it
 * in a page shell. Edit the modal, run the script, both surfaces agree.
 *
 * Deliberately regex over a DOM parser: the repo has one devDependency
 * (Playwright) and the markup it reads is written right here, in a shape this
 * file asserts on. If an extraction ever misses, the script fails loudly
 * instead of writing half a page.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { join } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1");
const CHECK = process.argv.includes("--check");
const ORIGIN = "https://bylx.dev";

/* Normalised to LF before anything is matched: .gitattributes normalises on
   commit, so a Windows working copy has CRLF on disk and every multi-line
   marker below ("        </div>\n      </section>") would miss. */
const html = readFileSync(join(ROOT, "index.html"), "utf8").replace(/\r\n/g, "\n");

/* The same stamp index.html carries, so a work page never loads a stale
   stylesheet from Hostinger's edge (see CLAUDE.md § Cache). */
const stamp = html.match(/href="styles\.css\?v=([a-z0-9]+)"/)?.[1];
if (!stamp) throw new Error("no ?v= stamp in index.html — run stamp-assets.mjs first");

const MODAL = /<div class="modal pixel-modal" id="casestudy-([a-z0-9]+)-modal"[^>]*?data-work-slug="([^"]+)"\s+data-work-title="([^"]+)"\s+data-work-description="([^"]+)">/g;

const pages = [];
for (const [, key, slug, title, description] of html.matchAll(MODAL)) {
  const from = html.indexOf(`id="casestudy-${key}-modal"`);
  const headingMatch = html.slice(from).match(/<h2 id="casestudy-[a-z0-9]+-title">([\s\S]*?)<\/h2>/);
  const bodyStart = html.indexOf('<div class="modal-body case-study-body">', from);
  const bodyEnd = html.indexOf("        </div>\n      </section>", bodyStart);
  if (!headingMatch || bodyStart === -1 || bodyEnd === -1) {
    throw new Error(`could not extract the case study for "${slug}" — has the modal markup changed?`);
  }

  const body = html
    .slice(bodyStart + '<div class="modal-body case-study-body">'.length, bodyEnd)
    /* The permalink points at the page you are already on. */
    .replace(/\s*<p class="cs-permalink">[\s\S]*?<\/p>\n/, "\n")
    /* In the dialog the case-study title is an <h2>, so the section headings
       are <h3> and the outline is right. On the page the title becomes the
       <h1>, which would leave h1 → h3 — a skipped level, and a broken outline
       for anyone navigating by headings. The class carries the styling, so
       demoting the tag changes nothing visually. */
    .replace(/<h3 class="cs-heading">([\s\S]*?)<\/h3>/g, '<h2 class="cs-heading">$1</h2>')
    .trimEnd();

  pages.push({ key, slug, title, description, heading: headingMatch[1].trim(), body });
}

if (!pages.length) throw new Error("no case-study modals found in index.html");

const esc = (text) => text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

function render(page, all) {
  const url = `${ORIGIN}/work/${page.slug}/`;
  const others = all.filter((other) => other.slug !== page.slug);

  return `<!DOCTYPE html>
<html lang="en" class="is-work-page">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />

  <!-- Generated by scripts/build-work-pages.mjs from the case-study modal in
       index.html. Do not edit here: edit the modal and run npm run build. -->
  <title>${esc(page.title)} · bylx.dev</title>
  <meta name="description" content="${esc(page.description)}" />
  <link rel="canonical" href="${url}" />
  <meta property="og:title" content="${esc(page.title)}" />
  <meta property="og:description" content="${esc(page.description)}" />
  <meta property="og:url" content="${url}" />
  <meta property="og:type" content="article" />
  <meta property="og:image" content="${ORIGIN}/og-image.png" />
  <meta property="og:image:width" content="1200" />
  <meta property="og:image:height" content="630" />
  <meta property="og:site_name" content="bylx.dev" />
  <meta name="twitter:card" content="summary_large_image" />
  <meta name="theme-color" content="#09051b" />

  <script type="application/ld+json">
    {
      "@context": "https://schema.org",
      "@graph": [
        {
          "@type": "CreativeWork",
          "@id": "${url}#work",
          "name": ${JSON.stringify(page.title)},
          "headline": ${JSON.stringify(page.heading)},
          "description": ${JSON.stringify(page.description)},
          "url": "${url}",
          "inLanguage": "en",
          "author": { "@id": "${ORIGIN}/#aline" },
          "isPartOf": { "@id": "${ORIGIN}/#site" }
        },
        {
          "@type": "BreadcrumbList",
          "itemListElement": [
            { "@type": "ListItem", "position": 1, "name": "bylx.dev", "item": "${ORIGIN}/" },
            { "@type": "ListItem", "position": 2, "name": "Work", "item": "${ORIGIN}/#projects" },
            { "@type": "ListItem", "position": 3, "name": ${JSON.stringify(page.heading)} }
          ]
        }
      ]
    }
  </script>

  <link rel="icon" href="/assets/logo/bylx_logo_semdev.png" type="image/png">
  <link rel="preconnect" href="https://fonts.googleapis.com" />
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />
  <link
    href="https://fonts.googleapis.com/css2?family=Pixelify+Sans:wght@400..700&family=Press+Start+2P&display=swap"
    rel="stylesheet"
  />
  <link rel="stylesheet" href="/styles.css?v=${stamp}" />

  <!-- Hovering a case-study link starts fetching it. "moderate" waits for the
       hover rather than firing on load: six pages, no idea which one the
       reader wants, and prefetch (not prerender) keeps it cheap. -->
  <script type="speculationrules">
    {
      "prefetch": [
        { "where": { "href_matches": "/work/*" }, "eagerness": "moderate" },
        { "urls": ["/"], "eagerness": "moderate" }
      ]
    }
  </script>
</head>
<body>
  <main class="work-page">
    <nav class="work-crumbs" aria-label="Breadcrumb">
      <a href="/">bylx.dev</a> / <a href="/#projects">work</a> / ${esc(page.slug)}
    </nav>

    <article class="work-sheet">
      <header class="modal-header work-header">
        <h1>${page.heading}</h1>
        <a class="work-back" href="/#projects" aria-label="Back to all work"><span aria-hidden="true">←</span> back</a>
      </header>

      <div class="modal-body case-study-body">
${page.body}
      </div>
    </article>

    <nav class="work-more" aria-label="Other case studies">
      <p class="work-more-label">More work</p>
${others.map((other) => `      <a href="/work/${other.slug}/">${esc(other.heading.split(" — ")[0])}</a>`).join("\n")}
    </nav>
  </main>

  <footer class="site-footer">
    <div class="footer-inner">
      <p class="footer-brand"><a href="/">bylx.dev</a></p>
      <ul class="footer-links" aria-label="Social links">
        <li><a href="https://instagram.com/bylx.dev" target="_blank" rel="noopener noreferrer">Instagram</a></li>
        <li><a href="https://github.com/alinelx" target="_blank" rel="me noopener noreferrer">GitHub</a></li>
      </ul>
      <p class="footer-copy">© 2026 Aline Lopes Xavier · Built with vanilla HTML, CSS &amp; JS.</p>
    </div>
  </footer>

  <div class="sakura-cursor" aria-hidden="true"></div>
  <div class="cursor" aria-hidden="true"></div>

  <script type="module" src="/js/work.js?v=${stamp}"></script>
</body>
</html>
`;
}

const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/build-work-pages.mjs. The homepage plus one URL per
     case study: since 2026-09 the case studies are real pages, not only
     modals of "/". -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
  <url>
    <loc>${ORIGIN}/</loc>
    <lastmod>${new Date().toISOString().slice(0, 10)}</lastmod>
    <changefreq>monthly</changefreq>
    <priority>1.0</priority>
  </url>
${pages
  .map(
    (page) => `  <url>
    <loc>${ORIGIN}/work/${page.slug}/</loc>
    <lastmod>${new Date().toISOString().slice(0, 10)}</lastmod>
    <changefreq>monthly</changefreq>
    <priority>0.8</priority>
  </url>`
  )
  .join("\n")}
</urlset>
`;

/* lastmod moves every day the script runs, which would make --check fail on a
   file whose content is otherwise identical. Compare everything but the date. */
const undated = (text) => text.replace(/<lastmod>[^<]*<\/lastmod>/g, "");

let stale = false;
const outputs = [
  ...pages.map((page) => ({ path: join("work", page.slug, "index.html"), text: render(page, pages) })),
  { path: "sitemap.xml", text: sitemap, compare: undated },
];

for (const { path, text, compare = (t) => t } of outputs) {
  const full = join(ROOT, path);
  const before = existsSync(full) ? readFileSync(full, "utf8").replace(/\r\n/g, "\n") : "";
  if (compare(before) === compare(text)) continue;

  stale = true;
  if (!CHECK) {
    mkdirSync(join(full, ".."), { recursive: true });
    writeFileSync(full, text);
  }
  console.log(`${CHECK ? "stale" : "wrote"}  ${path}`);
}

if (CHECK && stale) {
  console.error("\nWork pages are out of date. Run: node scripts/build-work-pages.mjs");
  process.exit(1);
}

console.log(stale ? `\n${pages.length} case studies built` : `already current: ${pages.length} case studies`);
